export type TemplateSort = 'recommended' | 'name';

export function matchesTemplate(template: Template, query: string): boolean {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (tokens.length === 0) return true;
  const guide = templateGuides[template.id];
  const haystack = [
    template.name,
    template.description,
    template.category,
    guide?.bestFor,
    guide?.brief,
    ...(guide?.screens ?? []),
    ...(guide?.includes ?? []),
    ...(guide?.keywords ?? []),
  ]
    .filter((part): part is string => Boolean(part))
    .join('\n')
    .toLowerCase();
  return tokens.every((token) => haystack.includes(token));
}

export function sortTemplates(items: readonly Template[], sort: TemplateSort): Template[] {
  return [...items].sort((a, b) => {
    if (sort === 'name') return a.name.localeCompare(b.name);
    if (a.featured !== b.featured) return a.featured ? -1 : 1;
    if (a.cloneCount !== b.cloneCount) return b.cloneCount - a.cloneCount;
    return a.name.localeCompare(b.name);
  });
}
